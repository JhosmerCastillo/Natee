namespace Natee.Core.Models;

/// <summary>
/// Controls which sensitive or identifiable fields are redacted prior to generating PDF and JSON technical reports.
/// Defaults are privacy-preserving.
/// </summary>
public sealed record PrivacyRedactionOptions
{
    public bool RedactHostname { get; init; } = true;
    public bool RedactUsername { get; init; } = true;
    public bool RedactLocalIpAddresses { get; init; } = true;
    public bool RedactPublicIpAddresses { get; init; } = true;
    public bool RedactMacAddresses { get; init; } = true;
    public bool RedactInterfaceIdentifiers { get; init; } = false;
    public bool RedactWifiSsid { get; init; } = true;
    public bool RedactProcessNames { get; init; } = true;
    public bool RedactLocalFilePaths { get; init; } = true;
}

/// <summary>
/// Represents an alert or recovery notification generated by the monitoring engine.
/// </summary>
public sealed record AlertNotification
{
    public Guid Id { get; init; } = Guid.NewGuid();
    public DateTimeOffset TimestampUtc { get; init; } = DateTimeOffset.UtcNow;
    public AlertType AlertType { get; init; }
    public HealthStatus Severity { get; init; }
    public string Title { get; init; } = string.Empty;
    public string Message { get; init; } = string.Empty;
    public bool IsRecovery { get; init; }
}

/// <summary>
/// User-configurable settings for Natee monitoring, notifications, diagnostics, speed testing, privacy, and UI preferences.
/// </summary>
public sealed record NateeSettings
{
    public ThemePreference Theme { get; init; } = ThemePreference.System;
    public int MonitoringIntervalSeconds { get; init; } = 3;

    // Connectivity & Diagnostics
    public List<string> DiagnosticTargets { get; init; } = new() { "1.1.1.1", "8.8.8.8", "9.9.9.9" };
    public string DnsTestHostname { get; init; } = "cloudflare.com";
    public bool IncludeRouteTraceInDiagnosis { get; init; } = false;
    public int ProbeTimeoutMs { get; init; } = 2500;

    // Notifications & Anti-Spam
    public bool EnableConnectionAlerts { get; init; } = true;
    public bool EnableLatencyAlerts { get; init; } = true;
    public double LatencyThresholdMs { get; init; } = 120.0;
    public bool EnablePacketLossAlerts { get; init; } = true;
    public double PacketLossThresholdPercent { get; init; } = 5.0;
    public bool EnableDiskSpaceAlerts { get; init; } = true;
    public double MinFreeDiskPercentThreshold { get; init; } = 10.0;
    public bool EnableCpuAlerts { get; init; } = false;
    public double CpuThresholdPercent { get; init; } = 90.0;
    public bool EnableRamAlerts { get; init; } = false;
    public double RamThresholdPercent { get; init; } = 90.0;
    public int AlertCooldownSeconds { get; init; } = 300;
    public int ConsecutiveSamplesForAlert { get; init; } = 2;

    // Dashboard & Process Summary
    public int MaxProcessEntries { get; init; } = 5;
    public ProcessSortMode DefaultProcessSort { get; init; } = ProcessSortMode.CpuDescending;
    public bool StartInCompactMode { get; init; } = false;
    public bool MinimizeToTrayOnClose { get; init; } = true;
    public bool StartWithSession { get; init; } = false;

    // Local Persistence & Privacy
    public int HistoryRetentionDays { get; init; } = 14;
    public PrivacyRedactionOptions DefaultPrivacyOptions { get; init; } = new();

    // Speed Test
    public string SpeedTestProviderName { get; init; } = "Cloudflare Edge HTTPS";
    public string SpeedTestDownloadUrl { get; init; } = "https://speed.cloudflare.com/__down?bytes=15000000";
    public string SpeedTestUploadUrl { get; init; } = "https://speed.cloudflare.com/__up";
    public int SpeedTestUploadBytes { get; init; } = 5_000_000;
    public int SpeedTestTimeoutSeconds { get; init; } = 30;
}
